#!/usr/bin/env node
/**
 * Copy the built runtime into the self-contained skill.
 *
 * The skill must work without a global `obsidian-devkit` and without
 * `npm install`: `scripts/lib` is plain Node, `scripts/assets/templates`
 * is what `readAsset("../assets/templates/...")` expects, and the local
 * `scripts/package.json` gives Node the ESM module type.
 *
 * Run automatically after `npm run build` (postbuild), or manually:
 *   node scripts/sync-skill-runtime.mjs
 */
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const target = join(root, "skill", "obsidian-plugin-dev", "scripts");

const remove = (path) => rmSync(path, { recursive: true, force: true });
remove(join(target, "lib"));
remove(join(target, "assets"));
remove(join(target, "devkit.mjs"));
remove(join(target, "package.json"));
remove(join(target, "README.md"));
remove(join(target, "LICENSE"));
mkdirSync(join(target, "lib"), { recursive: true });
mkdirSync(join(target, "assets"), { recursive: true });

// Runtime modules only: no source maps, no .d.ts, no build metadata.
for (const file of readdirSync(join(root, "lib"))) {
  if (file.endsWith(".js")) {
    copyFileSync(join(root, "lib", file), join(target, "lib", file));
  }
}

// scaffold resolves templates as `../assets/templates/<file>` from `lib/`.
copyFileSync(join(root, "LICENSE"), join(target, "LICENSE"));
const templates = join(root, "assets", "templates");
mkdirSync(join(target, "assets", "templates"), { recursive: true });
for (const file of readdirSync(templates, { recursive: true, withFileTypes: true })) {
  if (!file.isFile()) continue;
  const source = join(file.parentPath ?? file.path, file.name);
  const relative = source.slice(templates.length + 1);
  const destination = join(target, "assets", "templates", relative);
  mkdirSync(dirname(destination), { recursive: true });
  copyFileSync(source, destination);
}

writeFileSync(
  join(target, "package.json"),
  `${JSON.stringify(
    {
      name: "obsidian-plugin-dev-scripts",
      version: pkg.version,
      private: true,
      type: "module",
      description: `Vendored obsidian-devkit runtime ${pkg.version} for the obsidian-plugin-dev skill.`,
    },
    null,
    2,
  )}\n`,
);

writeFileSync(
  join(target, "devkit.mjs"),
  `#!/usr/bin/env node
/**
 * Local entry point for the vendored obsidian-devkit runtime.
 * Use: node scripts/devkit.mjs <command> [options]
 */
import { runCli } from "./lib/commandline.js";

process.exitCode = await runCli(process.argv.slice(2), { cwd: process.cwd() });
`,
);

writeFileSync(
  join(target, "README.md"),
  `# Vendored runtime

This folder is generated by \`scripts/sync-skill-runtime.mjs\` from
\`dsh-obsidian-plugin-devkit\` v${pkg.version}. Do not edit it by hand.

- No global CLI and no \`npm install\` are needed to run it.
- Node.js >= 20 is required.
- \`scripts/lib/*.js\` is the built runtime; \`assets/templates\` is used by \`scaffold\`.
- The tool reports may still say \`obsidian-devkit\`; run the local entry instead:

\`\`\`bash
node scripts/devkit.mjs --version
node scripts/devkit.mjs scaffold ./my-plugin --id my-plugin --name "My Plugin"
node scripts/devkit.mjs build ./my-plugin
node scripts/devkit.mjs validate ./my-plugin
\`\`\`

Update this folder from the devkit repository with:

\`\`\`bash
npm run build          # runs postbuild -> sync-skill-runtime
# or
node scripts/sync-skill-runtime.mjs
\`\`\`
`,
);
