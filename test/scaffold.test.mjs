import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";

import { Fs } from "../lib/fs.js";
import { scaffold } from "../lib/scaffold.js";

const root = process.cwd();
const fs = new Fs();

async function tempDir(prefix) {
  return await mkdtemp(join(root, ".devkit", `test-${prefix}-`));
}

const options = {
  id: "test-hub",
  name: "Test Hub",
  description: "Generated by the scaffolding test.",
  author: "Knink",
  version: "0.1.0",
  minAppVersion: "1.13.0",
  desktopOnly: false,
  settingsStyle: "auto",
  overwrite: false,
  packageManager: "pnpm",
};

test("scaffold writes a complete project with valid JSON metadata", async () => {
  const dir = await tempDir("scaffold");
  const targetDir = join(dir, "test-hub").replace(/\\/g, "/");
  try {
    const result = await scaffold(fs, { ...options, targetDir }, { workspaceRoot: root });
    assert.equal(result.ok, true, result.report);
    assert.equal(result.style, "declarative");

    for (const file of [
      "manifest.json",
      "package.json",
      "tsconfig.json",
      "esbuild.config.mjs",
      "versions.json",
      "eslint.config.mts",
      "styles.css",
      ".gitignore",
      "LICENSE",
      "README.md",
      "AGENTS.md",
      "src/main.ts",
      "src/settings.ts",
    ]) {
      assert.ok(existsSync(join(targetDir, file)), `${file} was not written`);
    }

    const manifest = JSON.parse(await readFile(join(targetDir, "manifest.json"), "utf8"));
    assert.equal(manifest.id, "test-hub");
    assert.equal(manifest.version, "0.1.0");
    assert.equal(manifest.minAppVersion, "1.13.0");
    assert.equal(manifest.isDesktopOnly, false);

    const settings = await readFile(join(targetDir, "src/settings.ts"), "utf8");
    assert.match(settings, /getSettingDefinitions/);

    const versions = JSON.parse(await readFile(join(targetDir, "versions.json"), "utf8"));
    assert.equal(versions["0.1.0"], "1.13.0");
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("scaffold rejects metadata that the community reviewers reject", async () => {
  const dir = await tempDir("bad-name");
  const targetDir = join(dir, "bad").replace(/\\/g, "/");
  try {
    const result = await scaffold(
      fs,
      { ...options, targetDir, id: "obsidian-notes-plugin", name: "Obsidian Plugin" },
      { workspaceRoot: root },
    );
    assert.equal(result.ok, false);
    assert.match(result.report, /obsidian/i);
    assert.match(result.report, /end with "plugin"/i);
    assert.equal(existsSync(join(targetDir, "manifest.json")), false);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("scaffold refuses a non-empty directory unless overwrite is set", async () => {
  const dir = await tempDir("nonempty");
  const targetDir = join(dir, "project").replace(/\\/g, "/");
  try {
    await mkdir(targetDir, { recursive: true });
    await writeFile(join(targetDir, "keep.txt"), "user data", "utf8");
    const refused = await scaffold(fs, { ...options, targetDir }, { workspaceRoot: root });
    assert.equal(refused.ok, false);
    assert.match(refused.report, /not empty/i);

    const allowed = await scaffold(
      fs,
      { ...options, targetDir, overwrite: true },
      { workspaceRoot: root },
    );
    assert.equal(allowed.ok, true, allowed.report);
    assert.equal(
      await readFile(join(targetDir, "keep.txt"), "utf8"),
      "user data",
    );
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("declarative settings below 1.13.0 is a blocking problem", async () => {
  const dir = await tempDir("gate");
  const targetDir = join(dir, "legacy").replace(/\\/g, "/");
  try {
    const result = await scaffold(
      fs,
      { ...options, targetDir, minAppVersion: "1.8.0", settingsStyle: "declarative" },
      { workspaceRoot: root },
    );
    assert.equal(result.ok, false);
    assert.match(result.report, /1\.13\.0/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
