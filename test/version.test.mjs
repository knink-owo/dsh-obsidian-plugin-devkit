import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { Fs } from "../lib/fs.js";
import { bumpVersion } from "../lib/version.js";

const root = process.cwd();
const fs = new Fs();

function toPath(dir) {
  return dir.replace(/\\/g, "/");
}

async function makeProject() {
  const dir = await mkdtemp(join(root, ".devkit", "test-version-"));
  const project = toPath(dir);
  await writeFile(
    join(project, "manifest.json"),
    JSON.stringify(
      {
        id: "test-hub",
        name: "Test Hub",
        version: "0.1.0",
        minAppVersion: "1.13.0",
        description: "Generated by the version test.",
        author: "Knink",
        isDesktopOnly: false,
      },
      null,
      "\t",
    ) + "\n",
    "utf8",
  );
  await writeFile(
    join(project, "package.json"),
    JSON.stringify({ name: "test-hub", version: "0.1.0" }, null, "\t") + "\n",
    "utf8",
  );
  await writeFile(join(project, "versions.json"), JSON.stringify({ "0.1.0": "1.13.0" }, null, "\t") + "\n", "utf8");
  return project;
}

test("bump synchronises manifest, package and versions", async () => {
  const project = await makeProject();
  try {
    const result = await bumpVersion(
      fs,
      { projectDir: project, version: "0.2.0" },
      { workspaceRoot: root },
    );
    assert.equal(result.version, "0.2.0");
    assert.equal(result.changed.length, 3);

    const manifest = JSON.parse(await readFile(join(project, "manifest.json"), "utf8"));
    const pkg = JSON.parse(await readFile(join(project, "package.json"), "utf8"));
    const versions = JSON.parse(await readFile(join(project, "versions.json"), "utf8"));
    assert.equal(manifest.version, "0.2.0");
    assert.equal(pkg.version, "0.2.0");
    assert.equal(versions["0.2.0"], "1.13.0");
  } finally {
    await rm(join(root, project), { recursive: true, force: true });
  }
});

test("bump can move minAppVersion and updates the versions map", async () => {
  const project = await makeProject();
  try {
    await bumpVersion(
      fs,
      { projectDir: project, version: "0.2.0", minAppVersion: "1.14.0" },
      { workspaceRoot: root },
    );
    const manifest = JSON.parse(await readFile(join(project, "manifest.json"), "utf8"));
    const versions = JSON.parse(await readFile(join(project, "versions.json"), "utf8"));
    assert.equal(manifest.minAppVersion, "1.14.0");
    assert.equal(versions["0.2.0"], "1.14.0");
  } finally {
    await rm(join(root, project), { recursive: true, force: true });
  }
});

test("bump rejects invalid semver without touching files", async () => {
  const project = await makeProject();
  try {
    await assert.rejects(
      bumpVersion(fs, { projectDir: project, version: "v1.2" }, { workspaceRoot: root }),
      /Invalid version/,
    );
    const manifest = JSON.parse(await readFile(join(project, "manifest.json"), "utf8"));
    assert.equal(manifest.version, "0.1.0");
  } finally {
    await rm(join(root, project), { recursive: true, force: true });
  }
});
